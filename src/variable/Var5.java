package variable;

public class Var5 {
    public static void main(String[] args) {
        int a;
        a = 1; // 변수 선언과 초기화를 분리
        System.out.println(a);

        int b = 2; // 변수 선언과 동시에 초기화
        System.out.println(b);

        int c = 3, d = 4; // 한번에 여러 변수를 선언하고 초기화
        System.out.println(c);
        System.out.println(d);
    }
}
